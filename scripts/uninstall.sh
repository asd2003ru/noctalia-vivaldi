#!/usr/bin/env bash
# ============================================================================
# noctalia-vivaldi - uninstaller
#
# Removes only what this project installed:
#   * the "Vivaldi" template directory in Noctalia's community cache
#     (only when template.toml carries our marker)
#   * the generated stylesheet (only when it carries the generated marker)
#
# The custom-CSS directory itself is kept when other mods live in it, and
# Vivaldi's own settings are never touched.
# ============================================================================
set -euo pipefail

PROJECT_NAME="noctalia-vivaldi"
TEMPLATE_ID="vivaldi"
MARKER="noctalia-vivaldi"
CSS_MARKER="noctalia-vivaldi:generated"
CSS_FILE_NAME="noctalia.css"

CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
STATE_HOME="${XDG_STATE_HOME:-$HOME/.local/state}"

DEST_DIR="$STATE_HOME/noctalia/community-templates/$TEMPLATE_ID"
CSS_DIR_DEFAULT="$CONFIG_HOME/$PROJECT_NAME/css"

DRY_RUN=0
QUIET=0
FORCE=0
OUTPUT_DIR=""

usage() {
    cat <<'EOF'
Remove the Noctalia -> Vivaldi theme integration.

Usage: uninstall.sh [options]

Options:
  -n, --dry-run        Print what would be removed, change nothing
  -o, --output DIR     Directory containing the generated noctalia.css
                       (default: read from the installed template, otherwise
                        $XDG_CONFIG_HOME/noctalia-vivaldi/css)
  -f, --force          Remove the files even without this project's marker
  -q, --quiet          Only print warnings and errors
  -h, --help           Show this help
EOF
}

info() { [ "$QUIET" -eq 1 ] || printf '%s\n' "$*"; }
warn() { printf 'warning: %s\n' "$*" >&2; }
die()  { printf 'error: %s\n' "$*" >&2; exit 1; }

run() {
    if [ "$DRY_RUN" -eq 1 ]; then
        printf '[dry-run] %s\n' "$*"
    else
        "$@"
    fi
}

expand_xdg_token() {
    local path=$1
    path=${path/#\$XDG_CONFIG_HOME/${XDG_CONFIG_HOME:-$HOME/.config}}
    path=${path/#\$XDG_DATA_HOME/${XDG_DATA_HOME:-$HOME/.local/share}}
    path=${path/#\$XDG_STATE_HOME/${XDG_STATE_HOME:-$HOME/.local/state}}
    path=${path/#\$XDG_CACHE_HOME/${XDG_CACHE_HOME:-$HOME/.cache}}
    # shellcheck disable=SC2088
    case "$path" in
        "~/"*) path="$HOME/${path#\~/}" ;;
    esac
    printf '%s' "$path"
}

# Directory the installed descriptor writes into.
css_dir_from_descriptor() {
    [ -r "$DEST_DIR/template.toml" ] || return 1
    local raw
    raw=$(sed -n 's/^[[:space:]]*output_path[[:space:]]*=[[:space:]]*"\([^"]*\)".*/\1/p' "$DEST_DIR/template.toml" | head -n1)
    [ -n "$raw" ] || return 1
    dirname -- "$(expand_xdg_token "$raw")"
}

while [ $# -gt 0 ]; do
    case "$1" in
        -n|--dry-run) DRY_RUN=1 ;;
        -q|--quiet)   QUIET=1 ;;
        -f|--force)   FORCE=1 ;;
        -o|--output)  [ $# -ge 2 ] || die "--output needs an argument"; OUTPUT_DIR=$2; shift ;;
        -o=*|--output=*) OUTPUT_DIR=${1#*=} ;;
        -h|--help)    usage; exit 0 ;;
        *) die "unknown option: $1 (try --help)" ;;
    esac
    shift
done

main() {
    info "$PROJECT_NAME uninstaller"

    if [ -n "$OUTPUT_DIR" ]; then
        OUTPUT_DIR=$(expand_xdg_token "${OUTPUT_DIR%/}")
    else
        OUTPUT_DIR=$(css_dir_from_descriptor || true)
        [ -n "$OUTPUT_DIR" ] || OUTPUT_DIR="$CSS_DIR_DEFAULT"
    fi

    # 1. the template directory in Noctalia's community cache
    if [ -e "$DEST_DIR" ]; then
        if [ -f "$DEST_DIR/template.toml" ] && grep -qF "$MARKER" "$DEST_DIR/template.toml" 2>/dev/null; then
            run rm -rf -- "$DEST_DIR"
            info "removed: $DEST_DIR"
        elif [ "$FORCE" -eq 1 ]; then
            run rm -rf -- "$DEST_DIR"
            info "removed (forced): $DEST_DIR"
        else
            warn "not removing $DEST_DIR (not created by $PROJECT_NAME, use --force)"
        fi
    fi

    # 2. the generated stylesheet
    local css="$OUTPUT_DIR/$CSS_FILE_NAME"
    if [ -e "$css" ] && grep -qF "$CSS_MARKER" "$css" 2>/dev/null; then
        run rm -f -- "$css"
        info "removed: $css"
    elif [ -e "$css" ] && [ "$FORCE" -eq 1 ]; then
        run rm -f -- "$css"
        info "removed (forced): $css"
    elif [ -e "$css" ]; then
        warn "not removing $css (not generated by $PROJECT_NAME, use --force)"
    fi

    # 3. the directory itself, only when nothing else lives in it
    if [ -d "$OUTPUT_DIR" ] && [ -z "$(ls -A -- "$OUTPUT_DIR" 2>/dev/null)" ]; then
        run rmdir -- "$OUTPUT_DIR"
        info "removed empty directory: $OUTPUT_DIR"
    fi

    info ""
    if [ -n "$OUTPUT_DIR" ]; then
        info "Vivaldi still points its Custom UI Modifications at $OUTPUT_DIR."
        info "Clear that setting in Settings -> Appearance if you no longer need it."
    fi
    info "If 'Vivaldi' is still listed in Noctalia, disable it in"
    info "Settings -> Templates (Noctalia drops unknown ids on its own)."
}

main "$@"
